"""Build the single-file journal submission from the editable manuscript sources.

Springer Nature asks for one .tex file. This script inlines every \\input, replaces
references to Online Resource 1 with their numbers from supplement.aux, embeds
main.bbl and renames the figures Fig1, Fig2, ... in order of appearance.
Run after building main.pdf and supplement.pdf:
    python3 revision/manuscript/make_submission.py
"""
import re
import shutil
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "submission"
FIGURES = HERE.parent / "figures"


def inline(text):
    def repl(m):
        name = m.group(1)
        path = HERE / (name if name.endswith(".tex") else name + ".tex")
        return inline(path.read_text().rstrip("\n"))
    return re.sub(r"\\input\{([^}]+)\}", repl, text)


def supplement_labels():
    labels = {}
    for line in (HERE / "supplement.aux").read_text().splitlines():
        m = re.match(r"\\newlabel\{([^}]+)\}\{\{([^}]*)\}", line)
        if m:
            labels[m.group(1)] = m.group(2)
    return labels


def main():
    tex = inline((HERE / "main.tex").read_text())
    labels = supplement_labels()

    def ref(m):
        key = m.group(1)
        if key not in labels:
            raise SystemExit(f"Unresolved supplement label: {key}")
        return labels[key]
    tex = re.sub(r"\\ref\*\{supp-([^}]+)\}", ref, tex)
    tex = re.sub(r"\\usepackage\{xr\}\n\\externaldocument\[supp-\]\[nocite\]\{supplement\}\n", "", tex)
    assert "supp-" not in tex and "\\input{" not in tex

    tex = tex.replace("\\bibliography{references}", (HERE / "main.bbl").read_text().rstrip("\n"))
    tex = tex.replace("\\graphicspath{{../figures/}}\n", "")

    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir()
    figures = []

    def fig(m):
        name = m.group(2)
        if name not in figures:
            figures.append(name)
        new = f"Fig{figures.index(name) + 1}{Path(name).suffix}"
        shutil.copy(FIGURES / name, OUT / new)
        return m.group(1) + new + "}"
    tex = re.sub(r"(\\includegraphics(?:\[[^\]]*\])?\{)([^}]+)\}", fig, tex)

    header = ("% Single-file submission generated by revision/manuscript/make_submission.py.\n"
              "% Edit the sources in revision/manuscript/ instead.\n")
    (OUT / "manuscript.tex").write_text(header + tex)
    for name in ["sn-jnl.cls", "sn-basic.bst"]:
        shutil.copy(HERE / name, OUT / name)
    shutil.copy(HERE / "supplement.pdf", OUT / "ESM_1.pdf")

    for _ in range(2):
        subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error", "manuscript.tex"],
                       cwd=OUT, check=True, stdout=subprocess.DEVNULL)
    for ext in [".aux", ".log", ".out"]:
        (OUT / ("manuscript" + ext)).unlink(missing_ok=True)
    print(f"Wrote {OUT}: manuscript.tex, manuscript.pdf, {', '.join(f'Fig{i + 1}' for i in range(len(figures)))}, ESM_1.pdf")


if __name__ == "__main__":
    main()
