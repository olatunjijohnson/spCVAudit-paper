# Supplementary table comparing retained fits with the profile-search refits.
# Reads revision/results/profile-refit/ (written by compare_profile_refits.R).
# Usage: Rscript revision/exploratory/make_profile_refit_table.R
dir <- "revision/results/profile-refit"
h <- read.csv(file.path(dir, "nested-headlines.csv"))
s <- read.csv(file.path(dir, "sensitivity-headlines.csv"))
f <- read.csv(file.path(dir, "fit-changes.csv"))
stopifnot(nrow(h) == 4L, setequal(h$study, c("nested-rng", "nested-rng-profile", "nested-k10", "nested-k10-profile")))

num <- function(x, d = 5) formatC(x, format = "f", digits = d)
row_for <- function(study) {
  r <- h[h$study == study, ]
  sprintf("%s & %s & %s & %s (%s) & %s to %s & %s & %s & %s",
    if (grepl("profile", study)) "Profile search" else "Retained",
    num(r$mae_W), num(r$mae_J2), num(r$delta), num(r$mcse), num(r$lower), num(r$upper),
    num(r$reduction_percent, 1), num(r$strong_cell_delta), num(r$other_cells_delta))
}
sign_row <- function(study) {
  r <- s[s$study == study & s$diagnostic_model == "estimated_isotropic", ]
  sprintf("%s & %s & %s & %s & %s",
    if (grepl("profile", study)) "Profile search" else "Retained",
    num(100 * r$sign_accuracy[r$axis_ratio == 1], 1), num(100 * r$sign_accuracy[r$axis_ratio == 0.25], 1),
    num(r$mean_abs_proxy_error[r$axis_ratio == 1], 4), num(r$mean_abs_proxy_error[r$axis_ratio == 0.25], 4))
}
# Fits whose correlation scale moved by more than 1%, matched on configuration and fit.
material <- function(study) {
  fits <- function(stem) if (startsWith(study, "nested")) readRDS(stem)$fits else {
    z <- readRDS(stem)$results
    z <- z[z$scheme == "random" & z$diagnostic_model == "estimated_isotropic", ]
    data.frame(id = z$id, name = "full", range = z$fitted_range)
  }
  stem <- c(`nested-rng` = "nested-estimation-rng", `nested-k10` = "nested-estimation-k10",
            `sensitivity-rng` = "sensitivity-rng")[[study]]
  m <- merge(fits(file.path("revision/results", paste0(stem, ".rds"))),
             fits(file.path("revision/results", paste0(stem, "-profile.rds"))), by = c("id", "name"))
  mean(abs(log(m$range.y / m$range.x)) > log(1.01), na.rm = TRUE)
}
fit_row <- function(study, label) {
  r <- f[f$study == study, ]
  sprintf("%s & %s & %s & %s", label, format(r$fits, big.mark = ","),
          num(100 * r$changed_fraction, 1), num(100 * material(study), 1))
}

